function isDaouReportDraft(input: unknown): input is DaouReportDraft {
  if (!input || typeof input !== "object") return false;
  const r = input as Record<string, unknown>;
  return (
    typeof r.marketSection === "string" &&
    typeof r.competitionSection === "string" &&
    typeof r.summarySection === "string" &&
    // 2026-09-13 — promotionSection은 나중에 추가된 필드라, 모델이 빠뜨려도 초안 전체를 버리지
    // 않고 빈 값으로 받아들인다(아래 정규화에서 채운다).
    (r.promotionSection === undefined || typeof r.promotionSection === "string")
  );
}

export async function runDaouReportDraft(contextText: string): Promise<DaouReportDraft> {
  const client = getGeminiClient();
  if (!client) throw new Error("GEMINI_API_KEY가 설정되지 않았습니다.");
  const model = getGeminiModel();

  const response = await client.models.generateContent({
    model,
    contents: [
      {
        role: "user",
        parts: [{ text: `[이미 계산된 사실 자료]\n${contextText}\n\n위 자료만 근거로 평가기록 섹션을 작성하세요.` }],
      },
    ],
    config: {
      systemInstruction: SYSTEM_PROMPT,
      responseMimeType: "application/json",
      responseSchema: RESPONSE_SCHEMA,
    },
  });

  let parsed: unknown;
  try {
    parsed = JSON.parse(response.text ?? "");
  } catch {
    throw new Error("AI가 올바른 형식으로 응답하지 않았습니다. 다시 시도해주세요.");
  }
  if (!isDaouReportDraft(parsed)) {
    throw new Error("AI 응답 형식이 예상과 달랐습니다. 다시 시도해주세요.");
  }
  return { ...parsed, promotionSection: parsed.promotionSection ?? "" };
}
