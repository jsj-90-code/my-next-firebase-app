// 하는 방식은 "배치도에서 이 존이 물리적으로 어디 있는지 보고, 피난안내도에서 같은 위치를 찾아
// 번호를 확인하는" 것이므로, AI에게도 두 이미지를 같이 주고 위치로 대응시키게 한다.
